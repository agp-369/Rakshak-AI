#!/usr/bin/env python3
"""Build a raster MBTiles pack from OpenStreetMap tiles.

This is a build tool, not a runtime dependency. It downloads only the tiles
inside the requested bounding box and writes a standards-compliant MBTiles
archive in TMS row order.

Usage:
  python tools/build_mbtiles.py \
    --name dehradun-pilot \
    --bbox 30.25,77.96,30.37,78.12 \
    --min-zoom 12 --max-zoom 15 \
    --output assets/maps/dehradun_pilot.mbtiles

OpenStreetMap data is (c) OpenStreetMap contributors, ODbL 1.0.
Tile usage must follow https://operations.osmfoundation.org/policies/tiles/
Do not use this script for bulk scraping.
"""

from __future__ import annotations

import argparse
import math
import sqlite3
import sys
import time
from pathlib import Path

import requests

TILE_URL = "https://tile.openstreetmap.org/{z}/{x}/{y}.png"
USER_AGENT = "RakshakAI-field-map/1.0 (offline disaster pilot; contact: abhishekguptaagp)"


def deg2num(lat: float, lon: float, zoom: int) -> tuple[int, int]:
    n = 2**zoom
    x = int((lon + 180.0) / 360.0 * n)
    lat_rad = math.radians(lat)
    y = int((1.0 - math.asinh(math.tan(lat_rad)) / math.pi) / 2.0 * n)
    return x, y


def tile_range(bbox: tuple[float, float, float, float], zoom: int):
    south, west, north, east = bbox
    x_min, y_max = deg2num(south, west, zoom)
    x_max, y_min = deg2num(north, east, zoom)
    return x_min, x_max, y_min, y_max


def fetch_tile(session: requests.Session, z: int, x: int, y: int, retries: int = 4):
    url = TILE_URL.format(z=z, x=x, y=y)
    last_error: Exception | None = None
    for attempt in range(retries):
        try:
            response = session.get(url, timeout=20)
            if response.status_code == 200 and response.content:
                return response.content
            if response.status_code == 404:
                return None
            last_error = RuntimeError(f"HTTP {response.status_code} for {url}")
        except requests.RequestException as exc:
            last_error = exc
        time.sleep(1.5 * (attempt + 1))
    raise RuntimeError(f"Failed to fetch {url}") from last_error


def build(
    bbox,
    min_zoom,
    max_zoom,
    output: Path,
    name: str,
    delay: float,
    resume: bool,
):
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and not resume:
        output.unlink()

    db = sqlite3.connect(output)
    db.execute("CREATE TABLE IF NOT EXISTS metadata (name TEXT, value TEXT)")
    db.execute(
        "CREATE TABLE IF NOT EXISTS tiles (zoom_level INTEGER, tile_column INTEGER, "
        "tile_row INTEGER, tile_data BLOB)"
    )
    db.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS tile_index "
        "ON tiles (zoom_level, tile_column, tile_row)"
    )

    south, west, north, east = bbox
    metadata = {
        "name": name,
        "format": "png",
        "type": "baselayer",
        "version": "1",
        "scheme": "tms",
        "bounds": f"{west},{south},{east},{north}",
        "center": f"{(west + east) / 2:.6f},{(south + north) / 2:.6f},{min(max_zoom, 14)}",
        "minzoom": str(min_zoom),
        "maxzoom": str(max_zoom),
        "attribution": "(c) OpenStreetMap contributors, ODbL 1.0",
        "description": "Offline raster pack generated by Rakshak AI tools/build_mbtiles.py",
    }
    db.executemany(
        "INSERT OR REPLACE INTO metadata (name, value) VALUES (?, ?)",
        metadata.items(),
    )

    session = requests.Session()
    session.headers.update({"User-Agent": USER_AGENT, "Accept": "image/png"})

    total = 0
    for zoom in range(min_zoom, max_zoom + 1):
        x_min, x_max, y_min, y_max = tile_range(bbox, zoom)
        total += (x_max - x_min + 1) * (y_max - y_min + 1)

    existing = 0
    for zoom in range(min_zoom, max_zoom + 1):
        x_min, x_max, y_min, y_max = tile_range(bbox, zoom)
        for x in range(x_min, x_max + 1):
            for y in range(y_min, y_max + 1):
                tms_y = (2**zoom - 1) - y
                row = db.execute(
                    "SELECT 1 FROM tiles WHERE zoom_level = ? "
                    "AND tile_column = ? AND tile_row = ?",
                    (zoom, x, tms_y),
                ).fetchone()
                existing += row is not None
    print(
        f"Pack tiles: {total}; already present: {existing}; "
        f"to fetch: {total - existing}",
        flush=True,
    )

    fetched = 0
    try:
        for zoom in range(min_zoom, max_zoom + 1):
            x_min, x_max, y_min, y_max = tile_range(bbox, zoom)
            for x in range(x_min, x_max + 1):
                for y in range(y_min, y_max + 1):
                    tms_y = (2**zoom - 1) - y
                    row = db.execute(
                        "SELECT 1 FROM tiles WHERE zoom_level = ? "
                        "AND tile_column = ? AND tile_row = ?",
                        (zoom, x, tms_y),
                    ).fetchone()
                    if row is not None:
                        continue
                    data = fetch_tile(session, zoom, x, y)
                    if data is not None:
                        db.execute(
                            "INSERT OR REPLACE INTO tiles "
                            "(zoom_level, tile_column, tile_row, tile_data) "
                            "VALUES (?, ?, ?, ?)",
                            (zoom, x, tms_y, sqlite3.Binary(data)),
                        )
                        fetched += 1
                    if fetched % 10 == 0:
                        db.commit()
                        print(
                            f"  fetched {fetched}/{total - existing}",
                            flush=True,
                        )
                    if delay:
                        time.sleep(delay)
    finally:
        db.commit()
        db.close()
    print(
        f"Wrote {existing + fetched} tiles to {output} "
        f"({output.stat().st_size / 1024 / 1024:.2f} MB)"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--bbox", required=True, help="south,west,north,east")
    parser.add_argument("--min-zoom", type=int, required=True)
    parser.add_argument("--max-zoom", type=int, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--name", default="rakshak-offline-pack")
    parser.add_argument("--delay", type=float, default=0.05)
    parser.add_argument(
        "--resume",
        action="store_true",
        help="keep an existing archive and fetch only missing tiles",
    )
    args = parser.parse_args()

    try:
        south, west, north, east = [float(v) for v in args.bbox.split(",")]
    except ValueError:
        print("bbox must be south,west,north,east", file=sys.stderr)
        return 2
    if not (south < north and west < east):
        print("bbox must be ordered south<north and west<east", file=sys.stderr)
        return 2
    if not (0 <= args.min_zoom <= args.max_zoom <= 18):
        print("zoom must satisfy 0 <= min <= max <= 18", file=sys.stderr)
        return 2

    build(
        (south, west, north, east),
        args.min_zoom,
        args.max_zoom,
        args.output,
        args.name,
        args.delay,
        args.resume,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
